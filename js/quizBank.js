/**
 * 根據目前關卡與已作答題目 ID，隨機抽出一題不重複的題目
 * @param {Set<number> | Array<number>} usedIds - 已經做過的題目 ID 集合
 * @param {number} level - 目前關卡 (1, 2, 3)
 * @returns {object|null} 抽出題目物件
 */
window.getRandomQuiz = function(usedIds, level = 1) {
  const usedSet = usedIds instanceof Set ? usedIds : new Set(usedIds || []);
  const available = window.QUIZ_BANK.filter(q => !usedSet.has(q.id));
  if (available.length === 0) return null;

  // 根據規格 3.4 難度傾向篩選：
  // 第 1 區：easy 為主
  // 第 2 區：easy / medium 混合
  // 第 3 區：medium / hard 為主
  let preferredDiffs = ['easy'];
  if (level === 2) preferredDiffs = ['easy', 'medium'];
  else if (level >= 3) preferredDiffs = ['medium', 'hard'];

  const prioritized = available.filter(q => preferredDiffs.includes(q.difficulty));
  const pool = prioritized.length > 0 ? prioritized : available;

  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
};
